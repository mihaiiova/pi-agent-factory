import assert from 'node:assert/strict';
import { formatStatus, formatHistory, formatCost } from '../../extensions/project-state/presentation.mjs';
const sample = (key, cost, kind = 'main') => ({ key, kind, cost, usage: {}, agent: 'worker' });
const record = (samples, extra = {}) => ({ accounting: { version: 1, samples }, ...extra });
const status = formatStatus({ branch: 'spec/10-x', activeSpec: { number: 10 }, phase: 'in-progress', lastSessionId: 'sess-1' }, { totalCost: 0.125, coverage: { unpriced: 1 } });
assert.match(status, /spec: #10 \(in-progress\)/);
assert.match(status, /current session cost: \$0.1250 \(partial\)/);
assert.match(formatStatus(null, null), /current session cost: unavailable/);
const history = formatHistory([record([sample('a', 0.5)], { finalizedAt: '2026-09-17', activeSpec: { number: 10 }, workflow: 'spec-start', outcome: 'completed', summary: 'did the thing',
  subagentUsage: { agents: [{ agent: 'worker', status: 'completed' }] } }), { usage: { cost: { total: 100 } } }]);
assert.match(history, /cost=\$0.5000/);
assert.match(history, /worker\(completed\)/);
assert.match(history, /workflow=spec-start/);
assert.match(history, /cost=unavailable/);
assert.doesNotMatch(history, /\$100/);
assert.equal(formatHistory([]), 'No recorded sessions yet.');
const cost = formatCost({ totalCost: 0.25, mainCost: 0.2, subagentCost: 0.05 }, [record([sample('shared', 1), sample('sub', 2, 'subagent')]), record([sample('shared', 1), sample('unknown', null)])]);
assert.match(cost, /current session: \$0.2500/);
assert.match(cost, /project aggregate: \$3.0000 \(partial\)/);
assert.match(cost, /subagents \$2.0000/);
assert.match(formatCost(null, []), /project aggregate: unavailable/);
console.log('ok - presentation distinguishes partial/unknown cost, includes subagents and deduplicates shared evidence');
